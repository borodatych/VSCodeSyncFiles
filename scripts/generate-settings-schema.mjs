/**
 * Generates src/ui/settingsSchema.generated.ts from package.json
 * `contributes.configuration`.
 *
 * The settings panel used to carry its own hand-written list of keys plus
 * hardcoded labels and bounds (F11). It drifted: 92 settings are declared in
 * the manifest, the panel knew 67, and two of the keys it still rendered had
 * been deleted from the schema — VS Code rejects a write to an unregistered
 * key, so the webview reported "saved" while the value went nowhere.
 *
 * Descriptions come from the same `package.nls.json` (Russian base) VS Code itself uses,
 * so the panel and the built-in Settings UI cannot disagree about wording.
 *
 * Run automatically before esbuild via `npm run compile`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const nls = JSON.parse(readFileSync(join(root, "package.nls.json"), "utf8"));
const nlsEn = JSON.parse(readFileSync(join(root, "package.nls.en.json"), "utf8"));

const props = pkg.contributes?.configuration?.properties ?? {};
const PREFIX = "vscodesync.";

/** `%cfg.foo.description%` → the localised string, or the literal when inline. */
function resolveNls(value) {
  if (typeof value !== "string") return "";
  const m = /^%(.+)%$/.exec(value);
  if (!m) return value;
  return nls[m[1]] ?? nlsEn[m[1]] ?? "";
}

const entries = [];
for (const [fullKey, schema] of Object.entries(props)) {
  if (!fullKey.startsWith(PREFIX)) continue;
  const key = fullKey.slice(PREFIX.length);
  const entry = {
    key,
    type: Array.isArray(schema.type) ? schema.type[0] : (schema.type ?? "string"),
    // Half the manifest uses `markdownDescription` (VS Code renders both);
    // reading only `description` produced 22 blank labels.
    description: resolveNls(schema.description ?? schema.markdownDescription),
    default: schema.default,
  };
  if (schema.enum) entry.enum = schema.enum;
  if (Array.isArray(schema.enumDescriptions)) entry.enumDescriptions = schema.enumDescriptions;
  if (typeof schema.minimum === "number") entry.minimum = schema.minimum;
  if (typeof schema.maximum === "number") entry.maximum = schema.maximum;
  entries.push(entry);
}
entries.sort((a, b) => a.key.localeCompare(b.key));

const out = `/** Generated by scripts/generate-settings-schema.mjs — do not edit. */

export interface GeneratedSettingSchema {
  /** Key without the \`vscodesync.\` prefix. */
  key: string;
  type: string;
  description: string;
  default?: unknown;
  enum?: unknown[];
  enumDescriptions?: string[];
  minimum?: number;
  maximum?: number;
}

export const SETTINGS_SCHEMA: readonly GeneratedSettingSchema[] = ${JSON.stringify(entries, null, 2)};

/** Every declared key, in the order the panel renders them. */
export const SETTINGS_KEYS: readonly string[] = SETTINGS_SCHEMA.map((s) => s.key);
`;

writeFileSync(join(root, "src", "ui", "settingsSchema.generated.ts"), out);
console.log(`[generate-settings-schema] ${String(entries.length)} settings`);
