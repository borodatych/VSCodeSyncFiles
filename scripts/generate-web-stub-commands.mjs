/**
 * Generates src/webStubCommands.generated.ts from package.json contributes.commands.
 * Run automatically before esbuild via npm run compile.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const cmds = pkg.contributes?.commands ?? [];
const ids = cmds.map((c) => c.command).filter((x) => typeof x === "string" && x.length > 0);
const unique = [...new Set(ids)];

const out = `/** Generated by scripts/generate-web-stub-commands.mjs — do not edit. */
export const WEB_STUB_COMMAND_IDS: readonly string[] = ${JSON.stringify(unique, null, 2)};
`;

writeFileSync(join(root, "src", "webStubCommands.generated.ts"), out);
console.log(`[generate-web-stub-commands] ${String(unique.length)} command ids`);
